static void boot_draw_logo(uint16_t color)
{
    uint8_t hi = (uint8_t)(color >> 8);
    uint8_t lo = (uint8_t)(color & 0xFFU);

    lcd_set_window(LOGO_X, LOGO_Y, LOGO_W * LOGO_SCALE, LOGO_H * LOGO_SCALE);
    lcd_write_ram_prepare();

    for (uint8_t y = 0; y < LOGO_H; y++)
    {
        uint32_t row = s_org_logo[y];
        for (uint8_t sy = 0; sy < LOGO_SCALE; sy++)
        {
            uint32_t mask = 0x80000000UL;
            for (uint8_t x = 0; x < LOGO_W; x++)
            {
                uint8_t ph = (row & mask) ? hi : 0U;
                uint8_t pl = (row & mask) ? lo : 0U;
                LCD->LCD_RAM = ph; LCD->LCD_RAM = pl;
                LCD->LCD_RAM = ph; LCD->LCD_RAM = pl;
                LCD->LCD_RAM = ph; LCD->LCD_RAM = pl;
                mask >>= 1;
            }
        }
    }
}

static void boot_draw_glyph24(uint16_t x0, uint16_t y0, const uint8_t *bmp, uint16_t color)
{
    uint8_t hi = (uint8_t)(color >> 8);
    uint8_t lo = (uint8_t)(color & 0xFFU);

    lcd_set_window(x0, y0, GLYPH_W, GLYPH_H);
    lcd_write_ram_prepare();

    for (uint8_t y = 0; y < GLYPH_H; y++)
    {
        const uint8_t *row = &bmp[(uint16_t)y * 3U];
        for (uint8_t byte_i = 0; byte_i < 3U; byte_i++)
        {
            uint8_t b = row[byte_i];
            for (uint8_t bit = 0x80U; bit != 0U; bit >>= 1)
            {
                if (b & bit)
                {
                    LCD->LCD_RAM = hi;
                    LCD->LCD_RAM = lo;
                }
                else
                {
                    LCD->LCD_RAM = 0U;
                    LCD->LCD_RAM = 0U;
                }
            }
        }
    }
}

uint32_t boot_anim_start(void)
{
    static const uint16_t fade_ramp[8] = {
        0x2104U, 0x4208U, 0x630CU, 0x8410U,
        0xA514U, 0xC618U, 0xE71CU, 0xFFFFU,
    };

    uint32_t t0 = HAL_GetTick();
    lcd_clear(BLACK);

    /* Phase 1 (~200ms): emblem fade-in + horizontal divider expanding from center */
    for (uint8_t i = 0; i < 8U; i++)
    {
        boot_draw_logo(fade_ramp[i]);
        uint16_t half = (uint16_t)(((uint32_t)DIVIDER_HALF_MAX * (i + 1U)) / 8U);
        lcd_draw_hline((uint16_t)(160U - half), DIVIDER_Y, (uint16_t)(half * 2U), 0x6B4DU);
        delay_ms(24);
    }

    /* Phase 2 (~150ms): swift left-to-right reveal of 白玉楼制作所 */
    for (uint8_t i = 0; i < TITLE_GLYPHS; i++)
    {
        boot_draw_glyph24((uint16_t)(TITLE_X0 + (uint16_t)i * GLYPH_STEP),
                          TITLE_Y, s_org_name_24[i], WHITE);
        delay_ms(24);
    }

    /* Compact firmware subtitle using existing 12px ASCII font */
    char sub[24];
    snprintf(sub, sizeof(sub), "C3M1  %s", FW_VERSION_STR);
    uint16_t sw = (uint16_t)(strlen(sub) * 6U);
    g_back_color = BLACK;
    lcd_show_string((uint16_t)((320U - sw) / 2U), 190U, sw, 12U, 12U, sub, 0x8410U);

    return t0;
}

void boot_anim_finish(uint32_t start_tick)
{
    while ((HAL_GetTick() - start_tick) < BOOT_ANIM_TOTAL_MS)
    {
        delay_ms(5);
    }
    lcd_clear(BLACK);
}
